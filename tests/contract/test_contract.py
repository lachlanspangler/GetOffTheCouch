"""Contract tests: the exported JSON is exactly what the dashboard's generated types promise.

Runs against (1) a fresh export produced from recorded fixtures, and (2) whatever real/demo exports exist
in web/public/ (the self-healing loop runs this file right after `gotc run`).
"""

import json
import re
from pathlib import Path

import jsonschema
import pytest

from gotc.pipeline.run import run
from gotc.schema import SCHEMA_VERSION, CityFeed
from gotc.settings import ROOT
from tests.conftest import fast_client
from tests.integration.test_pipeline import REG, healthy_transport

SCHEMA_FILE = ROOT / "schema" / "cityfeed.schema.json"
TS_FILE = ROOT / "web" / "src" / "lib" / "feed.generated.ts"


def test_schema_file_is_up_to_date():
    on_disk = json.loads(SCHEMA_FILE.read_text())
    live = CityFeed.model_json_schema()
    on_disk.pop("$id", None)
    assert on_disk == json.loads(json.dumps(live)), "run `make schema` after changing gotc/schema.py"


def test_generated_ts_types_cover_the_schema():
    ts = TS_FILE.read_text()
    assert "GENERATED by `make schema`" in ts
    for name, model in json.loads(SCHEMA_FILE.read_text())["$defs"].items():
        if model.get("type") == "object":
            assert re.search(rf"export interface {name}\b", ts), f"{name} missing from TS types; run `make schema`"
            for prop in model.get("properties", {}):
                assert re.search(rf"\b{prop}\??:", ts), f"{name}.{prop} missing from TS types; run `make schema`"


def check_feed(doc: dict, *, demo: bool) -> None:
    jsonschema.validate(doc, json.loads(SCHEMA_FILE.read_text()))
    feed = CityFeed.model_validate(doc)
    assert feed.schema_version == SCHEMA_VERSION
    assert feed.is_demo == demo
    ids = set()
    for e in feed.events:
        assert e.is_demo == demo, "demo and real data must never mix"
        assert e.sources, f"{e.id} has no source"
        assert e.id not in ids
        ids.add(e.id)
        assert e.last_checked <= feed.generated_at
        if e.attendance:
            assert e.attendance.method and e.attendance.low <= e.attendance.mid <= e.attendance.high
        if e.tickets.pct_left:
            assert e.tickets.pct_left.method, "a % left number always explains itself"
        if e.price.is_free:
            assert not e.price.min and not e.price.max
        if e.stale:
            assert e.stale_reason


def test_fresh_fixture_export_honours_the_contract(db, settings):
    run(db, REG, settings, client=fast_client(healthy_transport()), geocode=False)
    from gotc.schema import CityDetails

    feeds = [f for f in (settings.web_data_dir / "cities").glob("*.json") if not f.name.endswith(".details.json")]
    for f in feeds:
        doc = json.loads(f.read_text())
        check_feed(doc, demo=False)
        det = CityDetails.model_validate_json(f.with_name(f.stem + ".details.json").read_text())
        assert set(det.events) == {e["id"] for e in doc["events"]}, "every card has details"
        assert all(not e.get("provenance") for e in doc["events"]), "provenance lives in the details file"
        assert any(d.provenance for d in det.events.values())
    index = json.loads((settings.web_data_dir / "index.json").read_text())
    assert index["schema_version"] == SCHEMA_VERSION and index["cities"]
    from gotc.schema import CityCoverage

    for c in index["cities"]:  # ADR-0008: every exported city carries its tier + coverage block
        cov = CityCoverage.model_validate(c["coverage"])
        assert c["tier"] == cov.tier and cov.tier in ("live", "beta")
        doc = json.loads((settings.web_data_dir / "cities" / f"{c['slug']}.json").read_text())
        assert doc["coverage"]["tier"] == cov.tier
    health = json.loads((settings.web_data_dir / "health.json").read_text())
    assert {"units", "log", "generated_at"} <= health.keys()


EXPORTS = sorted(p for p in (ROOT / "web" / "public" / "data" / "cities").glob("*.json") if ".details" not in p.name)
DEMOS = sorted(p for p in (ROOT / "web" / "public" / "demo" / "cities").glob("*.json") if ".details" not in p.name)


@pytest.mark.parametrize("path", EXPORTS, ids=[p.stem for p in EXPORTS])
def test_real_exports_honour_the_contract(path: Path):
    check_feed(json.loads(path.read_text()), demo=False)


@pytest.mark.parametrize("path", DEMOS, ids=[p.stem for p in DEMOS])
def test_demo_exports_are_flagged(path: Path):
    check_feed(json.loads(path.read_text()), demo=True)


